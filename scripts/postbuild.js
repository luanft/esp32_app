// After `react-scripts build`:
//  1. copy the hashed main.*.js / main.*.css to stable names (app.js / app.css)
//     so the index.html stored on the ESP32 never has to change between deploys
//  2. generate ../esp32c3/src/index_html.h (PROGMEM) pointing at the CDN copy
const fs = require('fs');
const path = require('path');

const pkg = require('../package.json');
const base = pkg.homepage.replace(/\/+$/, '');
const buildDir = path.join(__dirname, '..', 'build');
const find = (dir, ext) => {
  const f = fs.readdirSync(path.join(buildDir, 'static', dir)).find((n) => /^main\./.test(n) && n.endsWith(ext));
  if (!f) throw new Error(`main*${ext} not found in build/static/${dir}`);
  return path.join(buildDir, 'static', dir, f);
};

fs.copyFileSync(find('js', '.js'), path.join(buildDir, 'app.js'));
fs.copyFileSync(find('css', '.css'), path.join(buildDir, 'app.css'));

const html = `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">` +
  `<meta name="viewport" content="width=device-width,initial-scale=1">` +
  `<title>ESP32 Task Manager</title>` +
  `<link rel="stylesheet" href="${base}/app.css">` +
  `<script defer src="${base}/app.js"></script></head>` +
  `<body><noscript>You need to enable JavaScript.</noscript><div id="root"></div></body></html>`;

fs.writeFileSync(path.join(buildDir, 'esp32-index.html'), html);

const header = `// Generated by web_ui/scripts/postbuild.js - do not edit.\n` +
  `#pragma once\n#include <pgmspace.h>\n\n` +
  `static const char INDEX_HTML[] PROGMEM = R"rawliteral(${html})rawliteral";\n`;
const out = path.join(__dirname, '..', '..', 'esp32c3', 'src', 'index_html.h');
// The firmware lives in a sibling repo/folder; skip when absent (e.g. CI).
if (fs.existsSync(path.dirname(out))) {
  fs.writeFileSync(out, header);
  console.log(`ESP32 index (${html.length} bytes) -> ${out}`);
} else {
  console.log('esp32c3/src not found, skipping index_html.h');
}
